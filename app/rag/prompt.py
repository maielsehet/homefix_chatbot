from langchain_core.messages import SystemMessage, HumanMessage

def build_prompt(history_text, documents=None):
    if documents is None:
        documents = []

    # doc retrievements 
    if documents:
        context = "\n\n".join(
            doc.page_content for doc in documents
        )
    else:
        context = "لا يوجد سياق متاح حالياً، لأننا ما زلنا في مرحلة فهم المشكلة."



    system_prompt = """
أنت مساعد صيانة منزلية ذكي ومحاور لبوت HomeFix.

**قواعد اللعبة الأساسية:**
1. دورك هو فهم المشكلة بالتدريج. لا تقدم حلاً نهائياً إلا بعد أن تتأكد من تفاصيل المشكلة.
2. إذا كانت تفاصيل المشكلة غير واضحة (مثل: "المكيف عطلان" بدون ذكر الأعراض)، فلا تبحث في السياق، بل اطرح سؤالاً استكمالياً محدداً.
3. إذا كانت التفاصيل واضحة بما يكفي، استخدم السياق (الوثائق) المقدم لتوليد الإجابة. وإذا لم تجد الحل في السياق، أخبر المستخدم بذلك.
4. إذا تأكدت أن المشكلة معقدة وتحتاج إلى فني محترف (مثل: أعطال كهربائية، سباكة رئيسية)، اجعل جاهزية التوصية صحيحة.

**صيغة المخرجات (يجب أن تكون JSON فقط):**
يجب أن يكون ردك النهائي كائن JSON صحيحاً بالمفاتيح التالية:
{
  "summary": "ملخص المحادثة حتى الآن بالعربية (جملة أو جملتين)",
  "answer": "الحل النهائي بالعربية (اتركها فارغة '' إذا كنت لا تزال في مرحلة الاستفسار)",
  "follow_up": "سؤال الاستكمال بالعربية (ضعه null إذا كنت جاهزاً للإجابة النهائية)",
  "ready_for_recommendation": true/false
}

**تنبيهات هامة:**
- لا تختلق معلومات من خارج السياق.
- لا تذكر كلمة "السياق" أو "JSON" في الرد الذي سيراه المستخدم، فقط التزم بالهيكل المطلوب.
- أجب باللغة العربية.
"""


    human_prompt = f"""
تاريخ المحادثة حتى الآن:
{history_text}

-----------------------

السياق المرجعي (إن وُجد):
{context}

-----------------------

الآن، أخرج لي كائن JSON فقط، دون أي مقدمات أو تعليقات إضافية.
"""

    return [
        SystemMessage(content=system_prompt),
        HumanMessage(content=human_prompt)
    ]